import { Fragment, type CSSProperties } from "react";

interface Props {
  /** The number to count up to. */
  value: number;
  /**
   * Show it the way money is shown elsewhere in the app ("2,014,710", up to 2
   * decimals, a leading "-" if negative) instead of as a plain whole number.
   */
  grouped?: boolean;
  /** How long the count takes, in ms. */
  duration?: number;
  /**
   * Override when the count starts, in ms. By default it uses the surrounding
   * `--pop-delay` (set by the `pop-in` entrance animation on the parent), so a
   * number begins counting at the exact moment its tile begins to appear.
   */
  delay?: number;
  className?: string;
}

const MONEY = new Intl.NumberFormat("en-US", { maximumFractionDigits: 2 });
// CSS integers are 32-bit; beyond this the count can't be animated, so the
// number is simply shown as text.
const MAX_ANIMATABLE = 2_000_000_000;

/**
 * A number that counts up from 0 to `value`.
 *
 * It is driven entirely by CSS (see `.count-up` / `.count-up-grouped` in
 * globals.css), not by JavaScript. That keeps it in step with a `pop-in`
 * tile: both run as CSS animations from the same first paint with the same
 * delay, so there is no wait for the page's JS to load.
 *
 * The visible digits are generated by CSS and hidden from screen readers; the
 * real value is exposed instead, so nobody hears "3, 7, 12, 19…". With "reduce
 * motion" on, the final number is shown straight away.
 */
export function CountUp({ value, grouped = false, duration = 900, delay, className }: Props) {
  const timing = {
    "--count-duration": `${duration}ms`,
    ...(delay === undefined ? {} : { "--count-delay": `${delay}ms` }),
  };

  if (!grouped) {
    const style = { "--target": Math.round(value), ...timing } as CSSProperties;
    return (
      <span className={className}>
        <span aria-hidden="true" className="count-up" style={style} />
        <span className="sr-only">{Math.round(value)}</span>
      </span>
    );
  }

  // Same text the rest of the app shows for money, so the end state is identical.
  const text = MONEY.format(value);
  const negative = text.startsWith("-");
  const [intText, fraction] = (negative ? text.slice(1) : text).split(".");
  const target = Number(intText.replace(/,/g, ""));

  if (!Number.isFinite(target) || target > MAX_ANIMATABLE) {
    return <span className={className}>{text}</span>;
  }

  const style = { "--target": target, ...timing } as CSSProperties;
  const v = (expr: string) => ({ "--v": expr }) as CSSProperties;

  return (
    <span className={className}>
      {/* Shown only where the CSS maths below isn't supported. */}
      <span className="cg-fallback" aria-hidden="true">{text}</span>
      <span aria-hidden="true" className="count-up-grouped" style={style}>
        {negative && "-"}
        {[3, 2, 1, 0].map((k) => {
          const t = `var(--t${k})`;
          const f = `var(--f${k})`; // 1 when a higher group exists
          return (
            <Fragment key={k}>
              {/* leading group: unpadded, blank unless this is the top group */}
              <span
                className={`cg ${k === 0 ? "cg-lead0" : "cg-lead"}`}
                style={v(k === 0 ? `calc((1 - ${f}) * ${t} - ${f})` : `calc((1 - ${f}) * ${t})`)}
              />
              {/* comma, only before a later group */}
              <span className="cg cg-comma" style={v(`calc(${f})`)} />
              {/* later groups: always 3 digits */}
              <span className="cg cg-pad" style={v(`calc(${f} * mod(${t}, 1000) + ${f} - 1)`)} />
            </Fragment>
          );
        })}
        {fraction !== undefined && `.${fraction}`}
      </span>
      <span className="sr-only">{text}</span>
    </span>
  );
}
